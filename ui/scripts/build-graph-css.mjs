/**
 * Post-build step — emits `dist/lib/graph.css`, the graph-components-only
 * stylesheet published as `@opentrace/opentrace/graph.css`.
 *
 * Unlike `dist/lib/opentrace.css` (the batteries-included `./style.css`, which
 * Vite produces by merging every entry's CSS — design-system tokens, themes,
 * resets, scrollbars, and unrelated feature CSS), this bundle contains ONLY the
 * CSS for the graph panel components exported from the package's main entry
 * (GraphToolbar, FilterPanel, DiscoverPanel, PhysicsPanel, GraphLegend,
 * GraphBadge, PanelResizeHandle, …).
 *
 * Those rules are token-driven (var(--primary), var(--border), …) and carry no
 * global selectors of their own, so a consumer with its own design system can
 * import this file and have the panels render in their theme without their
 * app-wide tokens, body, or scrollbars being clobbered.
 *
 * The component CSS lives co-located in src/components/panels/*.css. Globbing
 * that directory means any new panel CSS added upstream flows into the bundle
 * automatically. The rules are wrapped in `@layer opentrace` so they sit below
 * a consumer's unlayered styles in the cascade (defensively safe).
 *
 * The concatenation machinery is shared with build-detail-panels-css.mjs; see
 * scripts/lib/bundle-css.mjs.
 *
 * Usage: node scripts/build-graph-css.mjs  (runs as part of `npm run build:lib`)
 */

import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundleCss } from './lib/bundle-css.mjs';

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = resolve(__dirname, '..');

