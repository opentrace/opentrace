/**
 * Post-build step — emits `dist/lib/detail-panels.css`, the detail-panel-only
 * stylesheet published as `@opentrace/opentrace/detail-panels.css`.
 *
 * Mirrors scripts/build-graph-css.mjs (shared machinery in
 * scripts/lib/bundle-css.mjs), but scoped to the two fully prop-driven detail
 * panels exported from `@opentrace/opentrace/app-components`: NodeDetailsPanel
 * and EdgeDetailsPanel. A consumer with its own backend can render those two
 * standalone, but their CSS otherwise ships only inside the batteries-included
 * `dist/lib/opentrace.css` (`./style.css`), which also carries global tokens,
 * resets, and scrollbars that would clobber a consumer's own design system.
 * This bundle contains ONLY the detail panels' rules.
 *
 * The bundle is named for its actual contents (detail-panels), NOT for the
 * `app-components` JS entry — that entry also exports ChatPanel, SidePanel,
 * GraphViewer, etc., whose CSS must NOT be included here.
 *
 * Unlike build-graph-css.mjs (which globs src/components/panels/*.css), this
 * uses an explicit file list: the source directories hold unrelated CSS
 * (SidePanel.css, SettingsDrawer.css, the rest of the chat styles, …) that must
 * never flow in. The list also reaches beyond the panels' own two files to pull
 * in the shared markdown styles NodeDetailsPanel needs: it renders PR bodies and
 * markdown source through react-markdown as `.message-content .markdown-body`,
 * whose rules live in src/components/chat/markdown.css. Without those, a
 * standalone consumer would get styled panel chrome but a raw, unstyled markdown
 * body. (The `.pr-body-content` wrapper box is co-located in NodeDetailsPanel.css.)
 *
 * Those rules are token-driven (var(--primary), var(--border), …) and carry no
 * global selectors of their own, so a consumer with its own design system can
 * import this file and have the panels render in their theme without their
 * app-wide tokens, body, or scrollbars being clobbered. The rules are wrapped
 * in `@layer opentrace` so they sit below a consumer's unlayered styles in the
 * cascade (defensively safe).
 *
 * Usage: node scripts/build-detail-panels-css.mjs  (runs as part of `npm run build:lib`)
 */

